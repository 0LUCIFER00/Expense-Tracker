-- Receipt and invoice attachments on expenses.
--
-- The files themselves live in private Vercel Blob storage; this table holds
-- only what describes them and the storage key the server generated. Nothing
-- here changes an expense, a balance or a budget.
--
-- Additive only: two new tables and a trigger on the new table.

create table if not exists receipt_attachments (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid        not null references users (id) on delete cascade,
  -- Deleting the expense deletes its attachments (and, via the trigger below,
  -- queues their files for removal). Deleting an attachment never touches
  -- the expense.
  expense_id   uuid        not null references expenses (id) on delete cascade,
  -- Generated by the server (receipts/<user>/<expense>/<uuid>.<ext>); never
  -- taken from the uploaded file name.
  storage_key  text        not null unique,
  -- The name shown to the user, cleaned of paths and control characters.
  file_name    text        not null check (length(file_name) between 1 and 120),
  -- What the file's own bytes say it is, not what the browser claimed.
  content_type text        not null check (content_type in (
                 'image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  size_bytes   integer     not null check (size_bytes > 0 and size_bytes <= 4194304),
  created_at   timestamptz not null default now()
);

create index if not exists receipt_attachments_expense_idx
  on receipt_attachments (expense_id, created_at);

create index if not exists receipt_attachments_user_idx
  on receipt_attachments (user_id);

-- Files waiting to be removed from storage. Filled by the trigger whenever an
-- attachment row goes, however it goes (removed on its own, its expense
-- deleted, the whole account deleted), and emptied as each file is deleted.
-- A deletion that fails stays here and is retried by the daily job, so no
-- file is left behind in storage.
create table if not exists attachment_cleanup (
  storage_key text        primary key,
  queued_at   timestamptz not null default now(),
  attempts    integer     not null default 0,
  last_error  text
);

create or replace function queue_attachment_cleanup() returns trigger as $$
begin
  insert into attachment_cleanup (storage_key) values (old.storage_key)
  on conflict (storage_key) do nothing;
  return old;
end;
$$ language plpgsql;

drop trigger if exists receipt_attachments_queue_cleanup on receipt_attachments;
create trigger receipt_attachments_queue_cleanup
  after delete on receipt_attachments
  for each row execute function queue_attachment_cleanup();
